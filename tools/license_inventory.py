#!/usr/bin/env python3
"""Writes docs/THIRD_PARTY_LICENSES.md from `cargo metadata` for the shipped
binaries' normal dependency graph on the given target platforms."""
import json, subprocess, sys
from collections import defaultdict

TARGETS = ["aarch64-apple-darwin", "x86_64-unknown-linux-gnu", "x86_64-pc-windows-msvc"]
rows = {}
for t in TARGETS:
    meta = json.loads(subprocess.check_output(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", t]))
    pkgs = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    roots = [p["id"] for p in meta["packages"] if p["name"] in ("vault-desktop", "vault-cli")]
    seen, stack = set(), list(roots)
    while stack:
        i = stack.pop()
        if i in seen:
            continue
        seen.add(i)
        for d in nodes[i]["deps"]:
            if any(k["kind"] in (None, "build") for k in d["dep_kinds"]):
                stack.append(d["pkg"])
    for i in seen:
        p = pkgs[i]
        if p["source"] is None:
            continue
        key = (p["name"], p["version"])
        rows.setdefault(key, {"license": p.get("license") or "(see crate)", "repo": p.get("repository") or "", "targets": set()})
        rows[key]["targets"].add(t.split("-")[2] if t.count("-") >= 2 else t)

by_license = defaultdict(int)
for v in rows.values():
    by_license[v["license"]] += 1

out = ["# Third-party Rust crates", "",
       "Generated by `tools/license_inventory.py` from `cargo metadata` (normal and",
       "build dependencies of `vault-desktop` and `vault-cli`, for macOS, Linux and",
       "Windows targets). Dev-only and fuzzing dependencies are excluded.", "",
       f"Total crates: **{len(rows)}**", "", "## By license expression", "",
       "| License | Crates |", "|---|---|"]
for lic, n in sorted(by_license.items(), key=lambda x: -x[1]):
    out.append(f"| {lic} | {n} |")
out += ["", "## Crates", "", "| Crate | Version | License | Platforms |", "|---|---|---|---|"]
for (name, ver), v in sorted(rows.items()):
    out.append(f"| {name} | {ver} | {v['license']} | {', '.join(sorted(v['targets']))} |")
out += ["", "Bundled non-code assets (fonts, icons, wordlist) are listed in",
        "`crates/vault-desktop/assets/fonts/NOTICE.md` and `crates/vault-core/data/README.md`.", ""]
open(sys.argv[1] if len(sys.argv) > 1 else "docs/THIRD_PARTY_LICENSES.md", "w").write("\n".join(out))
print(len(rows), "crates")
